SET content = $$## 涉外遗嘱/继承规划附件

### 1. 适用法律
依据《民法典》继承编 (第 1133-1144 条)、《法律适用法》第 32-35 条。

### 2. 当事人基本信息声明
**本附件适用前提**:立遗嘱人为中国公民,或中国公民且长期居住中国境内。如不符合,应另行咨询当地律师。

### 3. 准据法选择
- 遗嘱方式: 符合立遗嘱人经常居所地法、国籍国法、遗嘱行为地法的均为有效
- 遗嘱实质: 适用立遗嘱人立遗嘱时或死亡时的经常居所地法或国籍国法
- 遗产管理: 动产适用被继承人死亡时经常居所地法, 不动产适用不动产所在地法

### 4. 境外资产继承流程
- 中国境内资产: 在中国法院办理继承公证
- 境外资产: 当地 Probate Court 程序, 需当地律师代理

### 5. 海牙遗嘱公约
中国尚未加入《海牙遗嘱处分形式公约》(1961), 故中国境内遗嘱在境外执行通常需重新办理公证认证手续。

### 6. 跨境认证流程 (海牙 Apostille)
- 中国境内文件送往海牙公约缔约国: 办理 Apostille (中国 2023.11.7 加入)
- 中国境内文件送往非缔约国: 中国外交部 + 目的国驻华使馆双认证

### 7. 税务告知(2026 年最新)

**7.1 中国境内**:
- 遗产税: 暂未开征
- 房产税/个税: **继承取得房产本身免税**, 但**后续处置(出售/出租)可能产生个税/增值税**
  - 出售时按"满五唯一"免征增值税,否则按差额征收 5.6%
  - 个税: 转让所得 × 20%(满五唯一免征)

**7.2 美国**(IRS 通胀调整, 2026):
- 联邦遗产税(Estate Tax)免征额: USD 13,990,000(单人)
- 夫妻联合: USD 27,980,000
- 超额累进税率 18%-40%
- **海外华人(非美国税务居民)仅就其美国境内资产纳税**

**7.3 英国**:
- 继承税(Inheritance Tax)免征额: GBP 325,000
- 自住房产额外免征(Residence Nil-Rate Band): GBP 175,000
- 超额累进 40%

**7.4 加拿大**:
- 无联邦遗产税
- 但有 Probate Fee(认证费): 各省不同, 约资产 0.5%-1.5%
- 资本利得税: 继承时按公允价值"视同出售", 但有 principal residence 免征

**7.5 澳大利亚**:
- 无联邦遗产税
- 但有资本利得税: 继承后处置时按持有期计算

**7.6 新加坡**:
- 2008 年起**取消遗产税**

**7.7 通用提示**:
各国税法复杂, 海外华人**强烈建议**在遗嘱中明确"税务居民身份"声明, 并委托中国大陆 + 境外居住国两地律师/税务师联合规划。

### 8. 遗嘱信托(Family Trust)

**8.1 中国大陆**:
- 目前境内信托主要通过《信托法》(2001)设立
- 家族信托(2013 起): 中信信托、平安信托等已开展业务
- **境内家族信托不能跨境直接持有境外资产**
- 跨境资产建议在境外(香港/新加坡/开曼/BVI)设立家族信托

**8.2 海外华人建议**:
- 境外资产 > USD 1M → 建议设立境外家族信托
- 涉及子女教育/医疗 → 建议配置人寿保险信托(IAT)
- 涉及多代传承 → 建议配置朝代信托(Dynasty Trust)

