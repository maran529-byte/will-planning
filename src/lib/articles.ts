export function getAllArticles(): Article[] {
  return ARTICLES.slice().sort((a, b) => (b.dateModified > a.dateModified ? 1 : -1));
}

export function getArticleBySlug(slug: string): Article | undefined {
  return ARTICLES.find((a) => a.slug === slug);
}

export function getArticlesByCategory(category: ArticleCategory): Article[] {
  return ARTICLES.filter((a) => a.category === category).sort((a, b) =>
    b.dateModified > a.dateModified ? 1 : -1,
  );
}

export function getAllSlugs(): string[] {
  return ARTICLES.map((a) => a.slug);
}

export function getAllCategorySlugs(): ArticleCategory[] {
  return ARTICLE_CATEGORIES.map((c) => c.slug);
}

/**
 * 改版 v11 (2026-06-29, GEO): 同分类内「上文 / 下文」导航
 * - 用于文章页底部横向导航, 引导用户站内深耕
 * - 返回 null 表示已是首/末篇
 */
export function getAdjacentArticles(slug: string): { prev: Article | null; next: Article | null } {
  const current = getArticleBySlug(slug);
  if (!current) return { prev: null, next: null };
  const siblings = getArticlesByCategory(current.category);
  const idx = siblings.findIndex((a) => a.slug === slug);
  return {
    prev: idx > 0 ? siblings[idx - 1] : null,
    next: idx < siblings.length - 1 ? siblings[idx + 1] : null,
  };
}
